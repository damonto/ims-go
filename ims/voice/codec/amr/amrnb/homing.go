var decoderHomingFirstSubframeParams = [...]int{
	Mode475:  7,
	Mode515:  7,
	Mode590:  7,
	Mode670:  7,
	Mode740:  7,
	Mode795:  8,
	Mode1020: 12,
	Mode1220: 18,
}

func encoderHomingFrame(pcm []int16) bool {
	if len(pcm) != FrameSamples {
		return false
	}
	for _, sample := range pcm {
		if sample != encoderHomingFrameSample {
			return false
		}
	}
	return true
}

func decoderHomingFrame(serial []byte, mode Mode) bool {
	return decoderHomingFrameN(serial, mode, len(decoderHomingParams[mode]))
}

func decoderHomingFrameFirst(serial []byte, mode Mode) bool {
	if mode < Mode475 || mode > Mode1220 {
		return false
	}
	return decoderHomingFrameN(serial, mode, decoderHomingFirstSubframeParams[mode])
}

func decoderHomingFrameN(serial []byte, mode Mode, count int) bool {
	if mode < Mode475 || mode > Mode1220 {
		return false
	}
	total, err := ParameterSerialBits(mode)
	if err != nil || len(serial) < total {
		return false
	}
	if len(serial) > total {
		serial = serial[:total]
	}
	params := Params{Mode: mode}
	if err := params.UnmarshalBinary(serial); err != nil {
		return false
	}
	want := decoderHomingParams[mode]
	if count > len(params.Values) || count > len(want) {
		return false
	}
	for i := range count {
		if params.Values[i] != want[i] {
			return false
		}
	}
	return true
}
